#!/usr/bin/env node
// Pulls current rating/review data from the Google Places API (New) and
// refreshes data/business.ts (rating + count) and data/reviews.ts
// (review text) in place. Run manually or on a schedule (e.g. a nightly
// GitHub Action) — this does NOT run on every visitor request, so it
// adds no latency or per-pageview API cost to the live site.
//
// Requires:
//   GOOGLE_PLACES_API_KEY  — API key from a billing-enabled Google Cloud
//                            project with the "Places API (New)" enabled
//   GOOGLE_PLACE_ID        — Halladay Plumbing's Place ID (find via
//                            https://developers.google.com/maps/documentation/places/web-service/place-id)
//
// Usage:  GOOGLE_PLACES_API_KEY=xxx GOOGLE_PLACE_ID=xxx node scripts/sync-google-reviews.mjs
//
// Known limitation: Google's Places API only ever returns up to 5
// "most relevant" reviews per place, regardless of the place's total
// review count — there is no API to page through all reviews. The
// rating and total review count fields ARE the full, real aggregate
// numbers; only the review *text* sample is capped at 5.

import { writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import path from "node:path";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(__dirname, "..");

const API_KEY = process.env.GOOGLE_PLACES_API_KEY;
const PLACE_ID = process.env.GOOGLE_PLACE_ID;

if (!API_KEY || !PLACE_ID) {
  console.error(
    "Missing GOOGLE_PLACES_API_KEY and/or GOOGLE_PLACE_ID environment variables. See the comment at the top of this script.",
  );
  process.exit(1);
}

async function main() {
  const url = `https://places.googleapis.com/v1/places/${PLACE_ID}`;
  const res = await fetch(url, {
    headers: {
      "X-Goog-Api-Key": API_KEY,
      "X-Goog-FieldMask": "rating,userRatingCount,googleMapsUri,reviews",
    },
  });

  if (!res.ok) {
    const body = await res.text();
    throw new Error(`Places API request failed (${res.status}): ${body}`);
  }

  const place = await res.json();
  const rating = place.rating ?? null;
  const reviewCount = place.userRatingCount ?? null;
  const placeUrl = place.googleMapsUri ?? "";
  const reviews = (place.reviews ?? []).map((r, i) => ({
    id: `google-sync-${i}-${(r.authorAttribution?.displayName ?? "reviewer").toLowerCase().replace(/[^a-z0-9]+/g, "-")}`,
    author: shortenAuthorName(r.authorAttribution?.displayName ?? "Google User"),
    rating: r.rating ?? 5,
    text: (r.text?.text ?? "").replace(/\s+/g, " ").trim(),
    tags: [],
    source: "google",
    date: r.publishTime ?? undefined,
  }));

  await updateBusinessFile(rating, reviewCount, placeUrl);
  await writeReviewsFile(reviews);

  console.log(`Synced: rating=${rating}, reviewCount=${reviewCount}, reviews pulled=${reviews.length} (Google caps this at 5).`);
  if (reviews.length > 0) {
    console.log("Review `tags` were left empty — tag each one with the relevant service id(s) from data/services.ts by hand.");
  }
}

function shortenAuthorName(fullName) {
  const parts = fullName.trim().split(/\s+/);
  if (parts.length < 2) return fullName;
  return `${parts[0]} ${parts[parts.length - 1][0]}.`;
}

async function updateBusinessFile(rating, reviewCount, placeUrl) {
  const filePath = path.join(ROOT, "data", "business.ts");
  const { readFile } = await import("node:fs/promises");
  let content = await readFile(filePath, "utf8");

  content = content.replace(/googleRating: [^,]+,/, `googleRating: ${rating ?? "null"} as number | null,`);
  content = content.replace(/googleReviewCount: [^,]+,/, `googleReviewCount: ${reviewCount ?? "null"} as number | null,`);
  if (placeUrl) {
    content = content.replace(/googlePlaceUrl: "[^"]*",/, `googlePlaceUrl: "${placeUrl}",`);
  }

  await writeFile(filePath, content, "utf8");
}

async function writeReviewsFile(reviews) {
  const filePath = path.join(ROOT, "data", "reviews.ts");
  const entries = reviews
    .map(
      (r) => `  {
    id: "${r.id}",
    author: "${r.author.replace(/"/g, '\\"')}",
    rating: ${r.rating},
    text: "${r.text.replace(/"/g, '\\"')}",
    tags: [], // TODO: tag with relevant service id(s) from data/services.ts
    source: "google",${r.date ? `\n    date: "${r.date}",` : ""}
  },`,
    )
    .join("\n");

  const content = `// Customer reviews.
//
// Auto-generated by scripts/sync-google-reviews.mjs on ${new Date().toISOString()}.
// Google's Places API caps this at the 5 most relevant reviews — this is
// not the full review list. Tag each review with the relevant service
// id(s) so it surfaces in the right filtered sections.

export interface Review {
  id: string;
  author: string; // first name + last initial, as shown on Google
  rating: 1 | 2 | 3 | 4 | 5;
  text: string;
  tags: string[]; // service ids this review relates to
  source: "google";
  date?: string; // ISO date, optional
}

export const reviews: Review[] = [
${entries}
];

export function getReviewsByTag(tag?: string): Review[] {
  if (!tag) return reviews;
  return reviews.filter((r) => r.tags.includes(tag));
}
`;

  await writeFile(filePath, content, "utf8");
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
